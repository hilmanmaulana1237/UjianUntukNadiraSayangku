function shuffleArray(arr) {
  const shuffled = [...arr];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

function buildQuizQuestions() {
  let allQuestions = [];

  // Shuffle topics but keep order somewhat - just shuffle within each topic
  const topicKeys = Object.keys(topicQuestions);
  for (const topic of topicKeys) {
    const shuffled = shuffleArray(topicQuestions[topic]);
    allQuestions.push(...shuffled.map(q => ({ ...q, topic })));
  }

  // Shuffle all regular questions
  allQuestions = shuffleArray(allQuestions);

  // Insert romantic questions every 5 questions
  let romanticIndex = 0;
  let result = [];
  for (let i = 0; i < allQuestions.length; i++) {
    result.push(allQuestions[i]);
    // After every 5th question (index 4, 9, 14, ...), insert a romantic question
    if ((i + 1) % 5 === 0 && romanticIndex < romanticQuestions.length) {
      result.push({
        ...romanticQuestions[romanticIndex],
        topic: "💕 Romantis",
        index: romanticIndex
      });
      romanticIndex++;
    }
  }

  return result;
}
